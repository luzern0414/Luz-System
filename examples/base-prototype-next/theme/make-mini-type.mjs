// The mini-program type scale (Luz-Design visual-design.html 小程序字阶), written to src/mini/type.generated.css.
//
//   node theme/make-mini-type.mjs          (build.mjs runs it after make-theme.mjs)
//
// The phone's text follows the user's WeChat font size: every size is a step of the ladder times --mp-fs (1 is the standard setting; the demo panel's
// 微信字体大小 sets it from 0.94 to 1.4, the care mode). Vant declares its component variables on :root as var(--van-font-size-md) and the like,
// which are resolved there, so changing the base sizes on .phone alone would not reach them: every font-size and line-height variable of the
// installed Vant is declared again on .phone, where the base sizes are the scaled ones.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const vantLib = resolve(root, 'node_modules/vant/lib')
const vars = new Map()
if (existsSync(vantLib)) {
  for (const dir of readdirSync(vantLib)) {
    const file = resolve(vantLib, dir, 'index.css')
    if (!existsSync(file)) continue
    for (const m of readFileSync(file, 'utf8').matchAll(/(--van-[a-z0-9-]+)\s*:\s*([^;}{]+)/g)) {
      const name = m[1]
      const value = m[2].trim()
      if (!/font-size|line-height/.test(name) || /^--van-(font-size|line-height)-(xs|sm|md|lg)$/.test(name)) continue
      if (/^\d+(\.\d+)?px$/.test(value)) vars.set(name, `calc(${value} * var(--mp-fs))`)
      else if (value.includes('var(')) vars.set(name, value)
    }
  }
}

const ladder = [12, 14, 16, 18, 20, 22, 24, 28, 32, 36, 40]
const css = `/* generated by theme/make-mini-type.mjs; do not edit. The mini-program type scale (12 / 14 / 16 / 18 / 22 / 28, with the price and big-number steps) times --mp-fs, the WeChat font-size factor. */
.phone {
  --mp-fs: 1;
${ladder.map((n) => `  --t${n}: calc(${n}px * var(--mp-fs));`).join('\n')}
  --van-font-size-xs: var(--t12); --van-font-size-sm: var(--t14); --van-font-size-md: var(--t16); --van-font-size-lg: var(--t18);
  --van-line-height-xs: calc(18px * var(--mp-fs)); --van-line-height-sm: calc(20px * var(--mp-fs)); --van-line-height-md: calc(24px * var(--mp-fs)); --van-line-height-lg: calc(26px * var(--mp-fs));
${[...vars].map(([k, v]) => `  ${k}: ${v};`).join('\n')}
  /* body text and controls are 16; the caption under an icon is 14; tags and badges are the 12 annotations; the title bar is 16, a dialog or sheet title 18 */
  --van-nav-bar-title-font-size: var(--van-font-size-md); --van-button-default-font-size: var(--van-font-size-md); --van-button-normal-font-size: var(--van-font-size-md);
  --van-button-small-font-size: var(--van-font-size-sm); --van-button-mini-font-size: var(--van-font-size-sm);
  --van-tabbar-item-font-size: var(--van-font-size-sm); --van-grid-item-text-font-size: var(--van-font-size-sm); --van-action-bar-icon-font-size: var(--van-font-size-sm);
  --van-tag-font-size: var(--van-font-size-xs); --van-badge-font-size: var(--van-font-size-xs); --van-card-font-size: var(--van-font-size-md);
  --van-card-title-line-height: calc(22px * var(--mp-fs)); --van-action-bar-icon-width: calc(64px * var(--mp-fs));
  /* the care mode (1.4 times) enlarges buttons and tick boxes with the text; spacing stays (WeChat 适老化指南 3.1) */
  --van-button-normal-height: calc(44px * var(--mp-fs)); --van-button-large-height: calc(50px * var(--mp-fs));
  --van-button-small-height: calc(32px * var(--mp-fs)); --van-button-mini-height: calc(24px * var(--mp-fs));
  --van-submit-bar-height: calc(50px * var(--mp-fs)); --van-submit-bar-button-width: calc(110px * var(--mp-fs)); --van-action-bar-height: calc(50px * var(--mp-fs)); --van-action-bar-button-height: calc(40px * var(--mp-fs));
  --van-checkbox-size: calc(20px * var(--mp-fs)); --van-radio-size: calc(20px * var(--mp-fs)); --van-tabbar-height: calc(50px * var(--mp-fs));
}
.phone .van-card__desc { font-size: var(--van-font-size-sm); }
/* a button keeps its text on one line and grows with it (the larger text sizes), a small button does not shrink in a row */
.phone .van-button { white-space: nowrap; }
.phone .van-button--small, .phone .van-button--mini { flex: none; padding: 0 calc(12px * var(--mp-fs)); }
`
writeFileSync(resolve(root, 'src/mini/type.generated.css'), css)
console.log(`mini type scale (${vars.size} Vant variables) -> src/mini/type.generated.css`)
